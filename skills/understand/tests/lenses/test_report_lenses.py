# --- Scenario: A diff report excludes changes made only on the base branch

@given(parsers.parse('"{file_path}" changed on "{base_branch}" after the current branch split from it'))
def _file_changed_on_base_after_split(lenses_world, file_path, base_branch):
    repo = lenses_world["repo"]
    target = repo / file_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("// initial base content\n", encoding="utf-8")
    subprocess.run(["git", "add", "."], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-m", f"initial {file_path}"], cwd=repo, check=True)

    # Branch feature-split
    subprocess.run(["git", "checkout", "-b", "feature-split"], cwd=repo, check=True, capture_output=True)

    # Switch back to base_branch and commit change
    subprocess.run(["git", "checkout", base_branch], cwd=repo, check=True, capture_output=True)
    target.write_text("// updated only on base branch\n", encoding="utf-8")
    subprocess.run(["git", "commit", "-am", f"update {file_path} on {base_branch}"], cwd=repo, check=True)

    # Switch back to feature branch
    subprocess.run(["git", "checkout", "feature-split"], cwd=repo, check=True, capture_output=True)


