@given(parsers.parse('"{file_path}" schedules failed payments again'))
def _file_schedules_failed_payments(lenses_world, file_path):
    repo = lenses_world["repo"]
    target = repo / file_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "# Schedules failed payments again with backoff algorithm\ndef handle_failed_payment(): pass\n",
        encoding="utf-8",
    )


@given(parsers.parse('no file in the repository contains the word "{word}"'))
def _no_file_contains_word(lenses_world, word):
    repo = lenses_world["repo"]
    for p in repo.rglob("*"):
        if p.is_file() and ".git" not in p.parts and not p.name.startswith("."):
            text = p.read_text(encoding="utf-8", errors="ignore")
            assert word.lower() not in text.lower(), f"File {p} unexpectedly contains {word}"


