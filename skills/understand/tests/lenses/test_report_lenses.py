# --- Scenario: A pull request report does not change the user's branch ---

@given('the user is on branch "main"')
def _user_on_branch_main(lenses_world):
    branch = subprocess.check_output(
        ["git", "branch", "--show-current"], cwd=lenses_world["repo"], text=True
    ).strip()
    assert branch == "main"


@when(parsers.parse("the user makes a report of pull request {pr_number:d}"))
def _report_of_pr(lenses_world, pr_number):
    repo = lenses_world["repo"]
    pr_key = str(pr_number)
    if pr_key not in lenses_world["pr_meta"]:
        head_sha = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=repo, text=True
        ).strip()
        lenses_world["pr_meta"][pr_key] = {
            "title": f"PR {pr_number}",
            "body": "PR description",
            "files": [{"path": "src/app.ts"}],
            "baseRefOid": head_sha,
            "headRefOid": head_sha,
        }
    meta = lenses_world["pr_meta"][pr_key]
    with patch("understand_lenses.pr.fetch_pr_metadata", return_value=meta):
        lenses_world["result"] = run_report(
            repo,
            lens=f"pr {pr_number}",
            base_dir=lenses_world["cache"],
        )


@then('the user is still on branch "main"')
def _user_still_on_branch_main(lenses_world):
    branch = subprocess.check_output(
        ["git", "branch", "--show-current"], cwd=lenses_world["repo"], text=True
    ).strip()
    assert branch == "main"


# --- Scenario: A pull request report shows the code as it is at the head of the pull request

@given(parsers.parse('pull request {pr_number:d} changes "{file_path}" on its branch'))
def _pr_changes_file_on_branch(lenses_world, pr_number, file_path):
    repo = lenses_world["repo"]
    pr_branch = f"pr-{pr_number}-branch"
    subprocess.run(["git", "checkout", "-b", pr_branch], cwd=repo, check=True, capture_output=True)
    target_file = repo / file_path
    target_file.parent.mkdir(parents=True, exist_ok=True)
    pr_content = f"// Head of PR {pr_number} for {file_path}\nconsole.log('pr head');\n"
    target_file.write_text(pr_content, encoding="utf-8")
    lenses_world["pr_files"][file_path] = pr_content
    subprocess.run(["git", "add", "."], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-m", f"PR {pr_number} changes {file_path}"], cwd=repo, check=True)
    head_sha = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=repo, text=True).strip()
    subprocess.run(["git", "checkout", "main"], cwd=repo, check=True, capture_output=True)

    base_sha = subprocess.check_output(["git", "rev-parse", "main"], cwd=repo, text=True).strip()
    lenses_world["pr_meta"][str(pr_number)] = {
        "title": f"PR {pr_number}",
        "body": "PR description",
        "files": [{"path": file_path}],
        "baseRefOid": base_sha,
        "headRefOid": head_sha,
    }


@then(parsers.parse('the source view of "{file_path}" shows the file as it is at the head of pull request {pr_number:d}'))
def _source_view_shows_pr_head(lenses_world, file_path, pr_number):
    result = lenses_world["result"]
    assert result is not None
    # Source views generated by renderer: run_dir / "src" / file_path + ".html"
    src_file = result.run_dir / "src" / f"{file_path}.html"
    assert src_file.exists(), f"Source view {src_file} does not exist"
    content = src_file.read_text(encoding="utf-8")
    expected = lenses_world["pr_files"][file_path]
    assert "Head of PR" in content or expected.strip() in content


