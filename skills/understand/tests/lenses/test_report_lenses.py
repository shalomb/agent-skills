# --- Scenario: Nodes outside the focus set stay on the map ---------------

@given(parsers.parse('a topic report where "{file_path}" is not in the focus set'))
def _topic_report_outside_focus(lenses_world, file_path):
    repo = lenses_world["repo"]
    outside = repo / file_path
    outside.parent.mkdir(parents=True, exist_ok=True)
    outside.write_text("def login(): pass\n", encoding="utf-8")

    billing = repo / "billing" / "retry.py"
    billing.parent.mkdir(parents=True, exist_ok=True)
    billing.write_text("def retry(): pass\n", encoding="utf-8")

    lenses_world["result"] = run_report(
        repo,
        lens="topic retry",
        base_dir=lenses_world["cache"],
    )
    assert file_path not in lenses_world["result"].focus_set


