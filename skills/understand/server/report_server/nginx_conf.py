"""Render a user-level nginx.conf for the report server. Pure: no I/O."""

from __future__ import annotations

import ipaddress
from dataclasses import dataclass
from pathlib import Path

MIN_UNPRIVILEGED_PORT = 1024


@dataclass(frozen=True)
class ServerParams:
    """Everything the generator needs. Paths must be absolute and already resolved."""

    listen: tuple[str, ...]
    port: int
    permitted: tuple[str, ...]
    shadow_root: Path
    src_root: Path
    run_dir: Path
    log_dir: Path
    temp_dir: Path


def _listen_directive(address: str, port: int) -> str:
    try:
        ip = ipaddress.ip_address(address)
    except ValueError:
        raise ValueError(f"listen address must be a specific IP address, got {address!r}") from None
    if ip.is_unspecified:
        raise ValueError(f"listen address must not be a wildcard, got {address!r}")
    if ip.version == 6:
        return f"listen [{ip}]:{port} ipv6only=on;"
    return f"listen {ip}:{port};"


def _allow_directive(cidr: str) -> str:
    try:
        network = ipaddress.ip_network(cidr, strict=True)
    except ValueError as error:
        raise ValueError(f"permitted range is not a canonical CIDR: {cidr!r} ({error})") from None
    if "/" not in cidr or network.prefixlen == 0:
        raise ValueError(f"permitted range must be a bounded CIDR, got {cidr!r}")
    return f"allow {network};"


_UNSAFE_PATH_CHARS = set('"\\$;{}\n\r\0')

# nginx needs a MIME table; /etc/nginx/mime.types is deliberately not included
# so that this server shares nothing with the system nginx.
_TYPES = """\
    types {
      text/html html htm;
      text/css css;
      text/plain txt md py;
      application/javascript js;
      application/json json;
      image/svg+xml svg;
      image/png png;
      image/jpeg jpg jpeg;
      image/x-icon ico;
    }
    default_type text/plain;
    charset utf-8;"""


def _path(path: Path) -> str:
    text = str(path)
    if not path.is_absolute() or _UNSAFE_PATH_CHARS & set(text):
        raise ValueError(f"path must be absolute and free of quotes, $, ; and braces: {text!r}")
    return text


def _serve_root_location(prefix: str, root: Path) -> str:
    # `disable_symlinks on` from the (already resolved) root: any symlink below
    # the root is refused. `if_not_owner` is not enough because the link and its
    # target are both owned by the user. A literal `from=` is used instead of
    # $document_root so that it does not depend on how alias sets that variable.
    path = _path(root).rstrip("/") + "/"
    return f"""\
    location {prefix} {{
      alias "{path}";
      disable_symlinks on from="{path}";
      index index.html;
      autoindex on;
    }}"""


def render_nginx_conf(params: ServerParams) -> str:
    if not params.listen:
        raise ValueError("listen needs at least one address")
    if not MIN_UNPRIVILEGED_PORT <= params.port <= 65535:
        raise ValueError(f"port must be {MIN_UNPRIVILEGED_PORT}-65535 (no root needed), got {params.port}")
    listens = "\n".join(f"    {_listen_directive(a, params.port)}" for a in params.listen)
    if not params.permitted:
        raise ValueError("permitted needs at least one range")
    rules = "\n".join(f"    {_allow_directive(r)}" for r in params.permitted)
    temp = _path(params.temp_dir)
    return f"""\
# Generated by report_server.nginx_conf. Do not edit.
pid "{_path(params.run_dir)}/nginx.pid";
error_log "{_path(params.log_dir)}/error.log" warn;
daemon off;
worker_processes 1;

events {{
  worker_connections 128;
}}

http {{
  access_log "{_path(params.log_dir)}/access.log";
  client_body_temp_path "{temp}/body";
  proxy_temp_path "{temp}/proxy";
  fastcgi_temp_path "{temp}/fastcgi";
  uwsgi_temp_path "{temp}/uwsgi";
  scgi_temp_path "{temp}/scgi";
  server_tokens off;
{_TYPES}

  server {{
{listens}
{rules}
    deny all;

    # Every refusal reads as "not found": a denied client, a hidden file and a
    # refused symlink (nginx answers 403 for a link as the last path component)
    # look the same. Denials stay visible in error.log ("access forbidden by rule").
    error_page 403 =404 @not_found;
    location @not_found {{
      return 404;
    }}

    # Any path segment that starts with a dot. A regex location wins over the
    # prefix locations below; nginx matches it on the decoded, normalised URI.
    location ~ "(^|/)\\." {{
      return 404;
    }}

{_serve_root_location("/r/", params.shadow_root)}

{_serve_root_location("/src/", params.src_root)}

    location / {{
      return 404;
    }}
  }}
}}
"""
