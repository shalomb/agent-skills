"""Render the one-time system nginx snippet and its sudoers rule. Pure: no I/O.

`report_server` (user-level instances) forbids wildcard listens, sudo and /etc;
this sibling package is the explicit, reviewable privileged path. It reuses the
tested directive builders so the access rules cannot drift between the two.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from report_server.nginx_conf import _TYPES, _allow_directive, _path, _serve_root_location

DEFAULT_SNIPPET_DIR = Path("/etc/nginx/agent-skills.d")
DEFAULT_ACCESS_LOG = Path("/var/log/nginx/agent-skills.access.log")
NGINX_BIN = "/usr/sbin/nginx"
SYSTEMCTL_BIN = "/usr/bin/systemctl"
_USER = re.compile(r"[a-z_][a-z0-9_-]{0,31}")


@dataclass(frozen=True)
class SystemParams:
    port: int
    permitted: tuple[str, ...]
    shadow_root: Path
    src_root: Path
    snippet_dir: Path = DEFAULT_SNIPPET_DIR
    access_log: Path = DEFAULT_ACCESS_LOG


def render_system_conf(params: SystemParams) -> str:
    """A conf.d snippet: one `server` block, for the http context of the stock nginx.conf."""
    if not 1 <= params.port <= 65535:
        raise ValueError(f"port must be 1-65535, got {params.port}")
    if not params.permitted:
        raise ValueError("permitted needs at least one range")
    rules = "\n".join(f"    {_allow_directive(r)}" for r in params.permitted)
    snippet_dir = _path(params.snippet_dir).rstrip("/")
    return f"""\
# Generated by report_server_system (ADR 0007). Do not edit; regenerate and reinstall:
#   skills/understand/server/install-system.sh
# Access is by source address only (allow-list below); the server answers any Host.
server {{
    listen {params.port} default_server;
    listen [::]:{params.port} ipv6only=on default_server;
    access_log "{_path(params.access_log)}";
    server_tokens off;
{_TYPES}

{rules}
    deny all;

    # Every refusal reads as "not found": a denied client, a hidden file and a
    # refused symlink all look the same (same rule as the user-level instances).
    error_page 403 =404 @not_found;
    location @not_found {{
      return 404;
    }}

    # Any path segment that starts with a dot.
    location ~ "(^|/)\\." {{
      return 404;
    }}

{_serve_root_location("/r/", params.shadow_root, index="report.html index.html")}

{_serve_root_location("/src/", params.src_root)}

    # Content owners drop `location` snippets here (owned by the user, applied by a reload).
    include {snippet_dir}/*.conf;

    location / {{
      return 404;
    }}
}}
"""


def render_sudoers(user: str) -> str:
    """Passwordless `nginx -t` and `systemctl reload nginx` for one user, nothing else."""
    if not _USER.fullmatch(user) or user == "root":
        raise ValueError(f"not a plain account name: {user!r}")
    return f"""\
# Installed by skills/understand/server/install-system.sh (ADR 0007).
# Lets {user} validate and reload nginx after editing /etc/nginx/agent-skills.d. Nothing else.
{user} ALL=(root) NOPASSWD: {NGINX_BIN} -t, {SYSTEMCTL_BIN} reload nginx
"""
